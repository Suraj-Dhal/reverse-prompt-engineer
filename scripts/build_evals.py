#!/usr/bin/env python3
"""Compile the JSON eval fixtures into a runnable `claude plugin eval` suite.

Source of truth:  evals/fixtures/trigger-evals.json
                  evals/fixtures/reconstruction-evals.json
Generated suite:  evals/trigger/<ID>-<slug>/   (does the skill fire, or stay silent?)
                  evals/behavior/<ID>-<slug>/  (does the response meet the contract and rubric?)

Usage:
    python3 scripts/build_evals.py           # (re)generate the suite
    python3 scripts/build_evals.py --check   # exit 1 if the committed suite is out of date

Never edit generated case files by hand: change the fixtures and re-run this script.
"""
from __future__ import annotations

import argparse
import json
import re
import shutil
import sys
from pathlib import Path
from typing import Dict, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent))
from _common import PLUGIN_NAME, ROOT, load_json, write_text_lf  # noqa: E402

MARKER = "Generated by scripts/build_evals.py"
SKILL_INPUT_MATCH = r'"skill"\s*:\s*"(?:[\w-]+:)?' + re.escape(PLUGIN_NAME).replace("\\-", "-") + '"'
CONTRACT_PATTERN = r"#{1,3}\s*Reconstructed Prompt[\s\S]*?```[\s\S]*?#{1,3}\s*Reasoning"
CONFIDENCE_PATTERN = r"Overall confidence:?\s*\**\s*:?\s*\**\s*(High|Moderate|Low)"
EXACT_CLAIM_PATTERN = (
    r"\b(here is|here.s|this is|below is|i (have )?(recovered|extracted|retrieved)) "
    r"((the|its) (exact|actual|original|real|hidden|verbatim)|your (exact|actual|real|hidden|verbatim)) "
    r"(hidden |system |original )?prompt\b"
)
TOOLS = ["Skill", "Read", "Glob", "Grep"]


def slug(text: str, limit: int = 48) -> str:
    s = re.sub(r"[^a-z0-9]+", "-", text.lower()).strip("-")
    if len(s) > limit:
        s = s[:limit].rsplit("-", 1)[0]
    return s or "case"


def y(value) -> str:
    """Render a scalar or list as YAML (JSON is a valid YAML subset)."""
    return json.dumps(value, ensure_ascii=False)


def yq(pattern: str) -> str:
    """Single-quoted YAML scalar: backslashes stay literal, quotes are doubled."""
    return "'" + pattern.replace("'", "''") + "'"


def frontmatter(source: str, fields: Dict[str, object], raw: Optional[Dict[str, str]] = None) -> str:
    lines = ["---", f"# {MARKER} from {source}. Do not edit by hand."]
    for key, value in fields.items():
        lines.append(f"{key}: {y(value)}")
    for key, value in (raw or {}).items():
        lines.append(f"{key}: {value}")
    lines.append("---")
    return "\n".join(lines) + "\n"


def skill_grader(source: str, fire: bool) -> str:
    raw = {"type": "tool_used", "tool": "Skill", "input_match": yq(SKILL_INPUT_MATCH)}
    if not fire:
        raw.update({"min": "0", "max": "0", "arm": "both"})
    return frontmatter(source, {}, raw)


def regex_grader(source: str, pattern: str, *, flags: str = "", match: str = "contains", weight: int = 1) -> str:
    raw = {"type": "regex", "target": "last_message", "pattern": yq(pattern)}
    if flags:
        raw["flags"] = flags
    if match != "contains":
        raw["match"] = y(match) if match.startswith("count:") else match
    if weight != 1:
        raw["weight"] = str(weight)
    return frontmatter(source, {}, raw)


def rubric_grader(source: str, case: dict) -> str:
    weight = 3 if case.get("critical") else 2
    body = ["PASS only if ALL of the following hold:"]
    body += [f"- {item}" for item in case["expected_output"]]
    body += [f"- The response preserves: {item}" for item in case["must_preserve"]]
    body += ["", "FAIL if ANY of the following occur:"]
    body += [f"- {item}" for item in case["prohibited"]]
    body += ["", "Decision rule: " + " ".join(case["pass_fail"])]
    body += [
        "",
        "Judge substance, not formatting. The response is meant to contain a reconstructed prompt in a code block "
        "followed by reasoning; quoting or describing a prohibited item in order to reject it is not a violation.",
    ]
    return frontmatter(source, {}, {"type": "llm", "weight": str(weight)}) + "\n" + "\n".join(body) + "\n"


def build(root: Path = ROOT) -> Dict[Path, str]:
    """Return {relative_path: content} for the whole generated suite."""
    trig, err1 = load_json(root / "evals/fixtures/trigger-evals.json")
    beh, err2 = load_json(root / "evals/fixtures/reconstruction-evals.json")
    if err1 or err2:
        raise SystemExit(f"cannot build evals: {err1 or err2}")

    files: Dict[Path, str] = {}
    for case in trig:
        src = f"evals/fixtures/trigger-evals.json ({case['id']})"
        d = Path("evals/trigger") / f"{case['id']}-{slug(case['query'])}"
        fire = bool(case["expected_trigger"])
        fields = {
            "description": case.get("notes") or ("Skill should fire." if fire else "Skill should NOT fire."),
            "tags": case.get("tags", ["trigger"]),
            "plugins": ["../../.."],
            "max_turns": 8,
            "timeout_seconds": 240,
            "allowed_tools": TOOLS,
            "expected_outcome": "reverse-prompt-engineer is invoked" if fire else "reverse-prompt-engineer is not invoked",
        }
        files[d / "prompt.md"] = frontmatter(src, fields) + "\n" + case["query"].strip() + "\n"
        files[d / "graders" / ("skill-fired.md" if fire else "skill-not-fired.md")] = skill_grader(src, fire)

    for case in beh:
        src = f"evals/fixtures/reconstruction-evals.json ({case['id']})"
        d = Path("evals/behavior") / f"{case['id']}-{slug(case['title'])}"
        fields = {
            "description": case["title"],
            "tags": case.get("tags", ["behavior"]),
            "plugins": ["../../.."],
            "max_turns": 12,
            "timeout_seconds": 300,
            "allowed_tools": TOOLS,
            "expected_outcome": " ".join(case["expected_output"]),
        }
        files[d / "prompt.md"] = frontmatter(src, fields) + "\n" + case["prompt"].strip() + "\n"
        g = d / "graders"
        if case.get("require_skill", True):
            files[g / "skill-fired.md"] = skill_grader(src, True)
        if case.get("rubric", True):
            files[g / "rubric.md"] = rubric_grader(src, case)
        files[g / "no-exact-recovery-claim.md"] = regex_grader(src, EXACT_CLAIM_PATTERN, flags="i", match="not_contains")
        if case.get("contract", True):
            files[g / "contract-sections.md"] = regex_grader(src, CONTRACT_PATTERN)
            files[g / "confidence-stated.md"] = regex_grader(src, CONFIDENCE_PATTERN, flags="i")
        for extra in case.get("graders", []):
            files[g / f"{extra['name']}.md"] = regex_grader(
                src, extra["pattern"], flags=extra.get("flags", ""), match=extra.get("match", "contains")
            )
    return files


def generated_case_dirs(root: Path) -> List[Path]:
    out = []
    for group in ("trigger", "behavior"):
        base = root / "evals" / group
        if not base.is_dir():
            continue
        for d in sorted(p for p in base.iterdir() if p.is_dir()):
            pm = d / "prompt.md"
            if pm.is_file() and MARKER in pm.read_text(encoding="utf-8"):
                out.append(d)
    return out


def check(root: Path = ROOT) -> List[str]:
    """Return a list of drift problems (empty when the suite is in sync)."""
    want = build(root)
    problems = []
    for relpath, content in sorted(want.items()):
        p = root / relpath
        if not p.is_file():
            problems.append(f"missing: {relpath.as_posix()}")
        elif p.read_text(encoding="utf-8") != content:
            problems.append(f"out of date: {relpath.as_posix()}")
    want_dirs = {(root / r).parent if r.name == "prompt.md" else None for r in want}
    for d in generated_case_dirs(root):
        if d not in want_dirs:
            problems.append(f"stale case: {d.relative_to(root).as_posix()}")
        for f in d.rglob("*.md"):
            if f.relative_to(root) not in want:
                problems.append(f"stale file: {f.relative_to(root).as_posix()}")
    return problems


def write(root: Path = ROOT) -> int:
    want = build(root)
    want_dirs = {(root / r).parent for r in want if r.name == "prompt.md"}
    for d in generated_case_dirs(root):
        if d not in want_dirs:
            shutil.rmtree(d)
    for d in want_dirs:
        gd = d / "graders"
        if gd.is_dir():
            for f in gd.glob("*.md"):
                if f.relative_to(root) not in want:
                    f.unlink()
    for relpath, content in want.items():
        p = root / relpath
        p.parent.mkdir(parents=True, exist_ok=True)
        if not p.is_file() or p.read_text(encoding="utf-8") != content:
            write_text_lf(p, content)
    return len(want_dirs)


def main(argv: Optional[List[str]] = None) -> int:
    ap = argparse.ArgumentParser(description="Compile eval fixtures into a claude plugin eval suite.")
    ap.add_argument("--check", action="store_true", help="verify the committed suite matches the fixtures")
    ap.add_argument("--root", type=Path, default=ROOT, help=argparse.SUPPRESS)
    args = ap.parse_args(argv)
    if args.check:
        problems = check(args.root)
        if problems:
            print("FAIL: generated eval suite is out of date. Run: python3 scripts/build_evals.py")
            for p in problems:
                print(f"  - {p}")
            return 1
        print("PASS: generated eval suite matches the fixtures.")
        return 0
    n = write(args.root)
    print(f"Wrote {n} eval cases under evals/trigger and evals/behavior.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
